function mdAdminRequireOperator(): ApiSession {
    $auth = DbhAuth::begin();
    $auth->fetchSessionData();
    mdAuthEnsureClientMetadata($auth);

    if (!canUserCreateCompany($auth->getLogin(), $auth)) {
        throw new ApiError('PERMISSION_DENIED', 'Keine Betreiber-Berechtigung fuer das Admin-Panel');
    }

    return $auth;
}

function mdAdminEnsureSchema(ApiSession $auth): void {
    mdAuthEnsureClientMetadata($auth);
    $auth->execute("
        CREATE TABLE IF NOT EXISTS auth.user_config (
            user_id integer NOT NULL REFERENCES auth.\"user\"(id) ON DELETE CASCADE,
            cfg_key text NOT NULL,
            cfg_value text,
            PRIMARY KEY (user_id, cfg_key)
        )
    ");
    $auth->execute("
        CREATE TABLE IF NOT EXISTS auth.admin_invites (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id integer REFERENCES auth.clients(id) ON DELETE CASCADE,
            email text NOT NULL,
            login text,
            name text,
            role text NOT NULL DEFAULT 'company_admin',
            status text NOT NULL DEFAULT 'pending',
            token_hash text NOT NULL UNIQUE,
            setup_allowed boolean NOT NULL DEFAULT false,
            email_sent boolean NOT NULL DEFAULT false,
            email_status text,
            invited_by_user_id integer REFERENCES auth.\"user\"(id) ON DELETE SET NULL,
            invited_by_login text,
            expires_at timestamp without time zone,
            accepted_at timestamp without time zone,
            itime timestamp without time zone NOT NULL DEFAULT now(),
            mtime timestamp without time zone
        )
    ");
    $auth->execute("CREATE INDEX IF NOT EXISTS admin_invites_client_idx ON auth.admin_invites(client_id)");
    $auth->execute("CREATE INDEX IF NOT EXISTS admin_invites_email_idx ON auth.admin_invites(lower(email))");
}

function mdAdminRequireHubAccess(): array {
    $auth = DbhAuth::begin();
    $auth->fetchSessionData();
    mdAdminEnsureSchema($auth);

    $isOperator = canUserCreateCompany($auth->getLogin(), $auth);
    $canManageCurrentCompany = $isOperator || $auth->checkPermissions(['admin'], false);

    if (!$canManageCurrentCompany) {
        throw new ApiError('PERMISSION_DENIED', 'Keine Berechtigung fuer das Admin-Panel');
    }

    return [
        'auth' => $auth,
        'is_operator' => $isOperator,
        'current_client_id' => intval($auth->getClientId()),
        'login' => $auth->getLogin(),
        'can_create_company' => $isOperator,
        'can_manage_users' => true,
        'can_edit_panel_settings' => $isOperator,
    ];
}

function mdAdminCanManageClient(array $context, int $clientId): bool {
    return !empty($context['is_operator']) || intval($context['current_client_id']) === $clientId;
}

function mdAdminRequireClientAccess(array $context, int $clientId): void {
    if (!mdAdminCanManageClient($context, $clientId)) {
        throw new ApiError('PERMISSION_DENIED', 'Keine Berechtigung fuer dieses Firmenpanel');
    }
}

function mdAdminBool($value): bool {
    return $value === true || $value === 1 || $value === '1' || $value === 'true' || $value === 't' || $value === 'on';
}

function mdAdminBoolValue($value): string {
    return mdAdminBool($value) ? 't' : 'f';
}

function mdAdminUserConfig(ApiSession $auth, int $userId): array {
    $rows = $auth->getAll(
        'SELECT cfg_key, cfg_value FROM auth.user_config WHERE user_id = :user_id',
        [':user_id' => $userId]
    );
    $config = [];
    foreach ($rows as $row) {
        $config[$row['cfg_key']] = $row['cfg_value'];
    }
    return $config;
}

function mdAdminSaveUserConfig(ApiSession $auth, int $userId, string $key, string $value): void {
    $auth->execute(
        'INSERT INTO auth.user_config (user_id, cfg_key, cfg_value)
         VALUES (:user_id, :cfg_key, :cfg_value)
         ON CONFLICT (user_id, cfg_key) DO UPDATE SET cfg_value = EXCLUDED.cfg_value',
        [
            ':user_id' => $userId,
            ':cfg_key' => $key,
            ':cfg_value' => $value,
        ]
    );
}

function mdAdminOperatorProfile(ApiSession $auth): array {
    $userId = intval($auth->getUserId());
    $user = $auth->getOne(
        'SELECT id, login, name, email
         FROM auth."user"
         WHERE id = :id',
        [':id' => $userId]
    );
    if (!$user) {
        throw new ApiError('USER_NOT_FOUND', 'Benutzer wurde nicht gefunden');
    }

    $config = mdAdminUserConfig($auth, $userId);
    return [
        'id' => intval($user['id']),
        'login' => $user['login'],
        'name' => $user['name'] ?? '',
        'email' => $user['email'] ?? '',
        'theme_mode' => in_array(($config['theme_mode'] ?? 'light'), ['light', 'dark', 'system'], true)
            ? $config['theme_mode']
            : 'light',
        'admin_debug' => mdAdminBool($config['admin_debug'] ?? false),
    ];
}

function mdAdminClientDefaults(ApiSession $auth, int $clientId): array {
    try {
        $company = mdAdminCompanyDbForClient($auth, $clientId);
        $rows = $company->getAll(
            "SELECT key, value
             FROM defaults_oserp
             WHERE key IN ('debug', 'company_name', 'email_smtp_host', 'email_username', 'email_address')"
        );
    } catch (\Throwable $e) {
        return [
            'debug_enabled' => false,
            'smtp_configured' => false,
            'health' => 'database_error',
            'health_error' => $e->getMessage(),
        ];
    }

    $defaults = [];
    foreach ($rows as $row) {
        $defaults[$row['key']] = $row['value'];
    }
    return [
        'debug_enabled' => mdAdminBool($defaults['debug'] ?? false),
        'smtp_configured' => !empty($defaults['email_smtp_host']) && (!empty($defaults['email_username']) || !empty($defaults['email_address'])),
        'health' => 'ok',
        'health_error' => '',
    ];
}

function mdAdminReadTail(string $path, int $maxBytes = 160000): array {
    if ($path === '' || !file_exists($path)) {
        return [
            'available' => false,
            'message' => 'Logdatei wurde noch nicht gefunden.',
            'path' => $path,
            'content' => '',
        ];
    }
    if (!is_readable($path)) {
        return [
            'available' => false,
            'message' => 'Logdatei ist fuer die Web-App nicht lesbar.',
            'path' => $path,
            'content' => '',
        ];
    }

    $size = filesize($path) ?: 0;
    $handle = fopen($path, 'rb');
    if (!$handle) {
        return [
            'available' => false,
            'message' => 'Logdatei konnte nicht geoeffnet werden.',
            'path' => $path,
            'content' => '',
        ];
    }
    if ($size > $maxBytes) {
        fseek($handle, -$maxBytes, SEEK_END);
    }
    $content = stream_get_contents($handle);
    fclose($handle);

    return [
        'available' => true,
        'message' => $size > $maxBytes ? 'Letzte Logzeilen geladen.' : 'Log geladen.',
        'path' => $path,
        'content' => $content ?: '',
    ];
}

function mdAdminSlugLogin(string $value): string {
    if (function_exists('iconv')) {
        $value = iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', $value) ?: $value;
    }
    $value = strtolower($value);
    $value = preg_replace('/[^a-z0-9._-]+/', '.', $value);
    $value = trim($value, '.-_');
    return $value ?: 'admin';
}

function mdAdminUniqueLogin(ApiSession $auth, string $preferredLogin, ?int $existingUserId = null): string {
    $base = mdAdminSlugLogin($preferredLogin);
    $login = $base;
    $suffix = 2;

    while (true) {
        $row = $auth->getOne('SELECT id FROM auth."user" WHERE login = :login', [':login' => $login]);
        if (!$row || ($existingUserId && intval($row['id']) === $existingUserId)) {
            return $login;
        }
        $login = $base . $suffix;
        $suffix++;
    }
}

function mdAdminGeneratePassword(): string {
    $alphabet = 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789';
    $password = '';
    for ($i = 0; $i < 18; $i++) {
        $password .= $alphabet[random_int(0, strlen($alphabet) - 1)];
    }
    return $password;
}

function mdAdminPanelUrl(): string {
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');
    $scheme = $https ? 'https' : 'http';
    $host = $_SERVER['HTTP_HOST'] ?? '';
    return $host ? $scheme . '://' . $host . '/admin.html' : '/admin.html';
}

function mdAdminClientConnection(ApiSession $auth, int $clientId): array {
    $client = $auth->getOne(
        'SELECT id, name, company_number, dbhost, dbport, dbname, dbuser, dbpasswd,
                master_data_locked, verification_status, setup_status
         FROM auth.clients
         WHERE id = :id
           AND COALESCE(is_system, false) = false',
        [':id' => $clientId]
    );
    if (!$client) {
        throw new ApiError('CLIENT_NOT_FOUND', 'Firma wurde nicht gefunden');
    }
    return $client;
}

function mdAdminCompanyDbForClient(ApiSession $auth, int $clientId): ApiDatabase {
    $client = mdAdminClientConnection($auth, $clientId);
    return new ApiDatabase(connectPDO($client['dbhost'], $client['dbport'], $client['dbname'], $client['dbuser'], $client['dbpasswd']));
}

function mdAdminEnsureEmployee(ApiDatabase $company, string $login, string $name, string $email): void {
    $company->execute(
        "INSERT INTO employee (login, name, sales, deleted, deleted_email, itime)
         VALUES (:login, :name, true, false, :email, now())
         ON CONFLICT (login) DO UPDATE SET
             name = COALESCE(NULLIF(:name_update, ''), employee.name),
             deleted = false,
             sales = true,
             deleted_email = COALESCE(NULLIF(:email_update, ''), employee.deleted_email),
             mtime = now()",
        [
            ':login' => $login,
            ':name' => $name ?: $login,
            ':email' => $email,
            ':name_update' => $name,
            ':email_update' => $email,
        ]
    );
}

function mdAdminEnsureGroup(ApiSession $auth, int $clientId, int $userId, string $role): string {
    $groupName = match ($role) {
        'setup_agent' => 'Setup-Mitarbeiter',
        'company_user' => 'Benutzer',
        default => 'Administratoren',
    };
    $group = $auth->getOne(
        'INSERT INTO auth."group" (name, mtime)
         VALUES (:name, now())
         ON CONFLICT (name) DO UPDATE SET mtime = now()
         RETURNING id',
        [':name' => $groupName]
    );
    $groupId = intval($group['id']);

    $auth->execute(
        'INSERT INTO auth.clients_groups (client_id, group_id) VALUES (:client_id, :group_id)
         ON CONFLICT DO NOTHING',
        [':client_id' => $clientId, ':group_id' => $groupId]
    );
    $auth->execute(
        'INSERT INTO auth.user_group (user_id, group_id) VALUES (:user_id, :group_id)
         ON CONFLICT DO NOTHING',
        [':user_id' => $userId, ':group_id' => $groupId]
    );

    $rights = $role === 'company_user'
        ? [
            'customer_vendor_edit',
            'invoice_edit',
            'sales_order_edit',
            'sales_quotation_edit',
            'sales_delivery_order_edit',
        ]
        : [
            'admin',
            'special_access',
            'customer_vendor_edit',
            'customer_vendor_all_edit',
            'invoice_edit',
            'sales_order_edit',
            'sales_quotation_edit',
            'sales_delivery_order_edit',
        ];
    foreach ($rights as $right) {
        $auth->execute(
            'INSERT INTO auth.group_rights (group_id, "right", granted)
             VALUES (:group_id, :right, true)
             ON CONFLICT (group_id, "right") DO UPDATE SET granted = true',
            [':group_id' => $groupId, ':right' => $right]
        );
    }

    return $groupName;
}

