function mdAdminSendInviteMail(ApiDatabase $company, array $invite, array $credentials): array {
    $config = mdAdminEmailConfig($company);
    $host = $config['email_smtp_host'] ?? '';
    $username = $config['email_username'] ?? '';
    $password = $config['email_password'] ?? '';
    if ($host === '' || $username === '' || $password === '') {
        return [
            'sent' => false,
            'status' => 'EMAIL_NOT_CONFIGURED',
            'message' => 'SMTP ist fuer diese Firma noch nicht konfiguriert.'
        ];
    }

    require_once __DIR__ . '/../email/smtp.class.php';

    $smtp = new SmtpClient(
        $host,
        intval($config['email_smtp_port'] ?? 465),
        $config['email_smtp_encryption'] ?? 'ssl',
        $username,
        $password
    );

    $fromEmail = $config['email_address'] ?? $username;
    $fromName = $config['email_from_name'] ?? 'MotorDesk';
    $roleLabel = match ($invite['role']) {
        'setup_agent' => 'Setup-Zugang',
        'company_user' => 'Benutzer-Zugang',
        default => 'Admin-Zugang',
    };
    $subject = 'MotorDesk ' . $roleLabel . ' fuer ' . $invite['client_name'];
    $bodyText = "Hallo {$invite['name']},\n\n"
        . "fuer {$invite['client_name']} wurde ein MotorDesk-Zugang angelegt.\n\n"
        . "Login: {$credentials['login']}\n"
        . "Passwort: {$credentials['password']}\n"
        . "Admin-Panel: {$credentials['admin_url']}\n\n"
        . "Bitte nach dem ersten Login das Passwort aendern.\n";
    $bodyHtml = nl2br(htmlspecialchars($bodyText, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'));

    try {
        $smtp->send(
            $fromEmail,
            $fromName,
            [['email' => $invite['email'], 'name' => $invite['name']]],
            $subject,
            $bodyHtml,
            $bodyText
        );
        return ['sent' => true, 'status' => 'SENT', 'message' => 'Einladung wurde per E-Mail verschickt.'];
    } catch (\Throwable $e) {
        return ['sent' => false, 'status' => 'SEND_FAILED', 'message' => $e->getMessage()];
    }
}

function getAdminOverview($data) {
    $context = mdAdminRequireHubAccess();
    $auth = $context['auth'];
    $clientFilters = ['COALESCE(c.is_system, false) = false'];
    if (!$context['is_operator']) {
        $clientFilters[] = 'c.id = :current_client_id';
    }
    $clientFilterSql = 'WHERE ' . implode(' AND ', $clientFilters);
    $clientParams = $context['is_operator'] ? [] : [':current_client_id' => $context['current_client_id']];

    $clients = $auth->getAll(
        'SELECT c.id AS code,
                c.name,
                c.company_number,
                c.dbname,
                c.is_default,
                c.master_data_locked,
                c.verification_status,
                c.setup_status,
                COUNT(cu.user_id) AS assigned_users
         FROM auth.clients c
         LEFT JOIN auth.clients_users cu ON cu.client_id = c.id
         ' . $clientFilterSql . '
         GROUP BY c.id, c.name, c.company_number, c.dbname, c.is_default,
                  c.master_data_locked, c.verification_status, c.setup_status
         ORDER BY c.company_number, c.name',
        $clientParams
    );

    $userFilters = ['COALESCE(c.is_system, false) = false'];
    if (!$context['is_operator']) {
        $userFilters[] = 'cu.client_id = :current_client_id';
    }
    $userFilterSql = 'WHERE ' . implode(' AND ', $userFilters);
    $userParams = $context['is_operator'] ? [] : [':current_client_id' => $context['current_client_id']];
    $users = $auth->getAll(
        'SELECT u.id,
                u.login,
                u.name,
                u.email,
                u.active,
                COUNT(DISTINCT cu.client_id) AS client_count
         FROM auth."user" u
         JOIN auth.clients_users cu ON cu.user_id = u.id
         JOIN auth.clients c ON c.id = cu.client_id
         ' . $userFilterSql . '
         GROUP BY u.id, u.login, u.name, u.email, u.active
         ORDER BY u.login',
        $userParams
    );

    $inviteFilters = ['COALESCE(c.is_system, false) = false'];
    if (!$context['is_operator']) {
        $inviteFilters[] = 'i.client_id = :current_client_id';
    }
    $inviteFilterSql = 'WHERE ' . implode(' AND ', $inviteFilters);
    $inviteParams = $context['is_operator'] ? [] : [':current_client_id' => $context['current_client_id']];
    $invites = $auth->getAll(
        'SELECT i.id,
                i.client_id,
                c.name AS client_name,
                c.company_number,
                i.email,
                i.login,
                i.name,
                i.role,
                i.status,
                i.setup_allowed,
                i.email_sent,
                i.email_status,
                i.invited_by_login,
                i.expires_at,
                i.itime
         FROM auth.admin_invites i
         LEFT JOIN auth.clients c ON c.id = i.client_id
         ' . $inviteFilterSql . '
         ORDER BY i.itime DESC
         LIMIT 50',
        $inviteParams
    );

    $clients = array_map(function ($client) use ($auth) {
        $runtime = mdAdminClientDefaults($auth, intval($client['code']));
        return array_merge($client, $runtime);
    }, $clients);

    resultInfo(true, '', [
        'clients' => $clients,
        'users' => $users,
        'invites' => $invites,
        'profile' => mdAdminOperatorProfile($auth),
        'context' => [
            'is_operator' => $context['is_operator'],
            'current_client_id' => $context['current_client_id'],
            'login' => $context['login'],
            'can_create_company' => $context['can_create_company'],
            'can_manage_users' => $context['can_manage_users'],
            'can_edit_panel_settings' => $context['can_edit_panel_settings'],
        ],
        'operator_users' => array_values(array_filter(array_map('trim', explode(',', COMPANY_ADMIN_USERS)))),
        'admin_url' => mdAdminPanelUrl(),
        'template_editor' => [
            'status' => 'planned',
            'areas' => ['invoice', 'sales_order', 'sales_quotation', 'email']
        ]
    ]);
}

function createAdminInvite($data) {
    $context = mdAdminRequireHubAccess();
    $auth = $context['auth'];

    $clientId = intval($data['client_id'] ?? 0);
    $email = strtolower(trim($data['email'] ?? ''));
    $name = trim($data['name'] ?? '');
    $role = trim($data['role'] ?? 'company_admin');
    $sendEmail = mdAdminBool($data['send_email'] ?? false);
    $resetPassword = !array_key_exists('reset_password', $data) || mdAdminBool($data['reset_password']);
    $expiresDays = max(1, min(30, intval($data['expires_days'] ?? 7)));
    $manualPassword = trim($data['password'] ?? '');

    if ($clientId <= 0) {
        throw new ApiError('CLIENT_REQUIRED', 'Bitte eine Firma auswaehlen');
    }
    mdAdminRequireClientAccess($context, $clientId);

    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
        throw new ApiError('INVALID_EMAIL', 'Bitte eine gueltige E-Mail-Adresse eintragen');
    }
    if (!in_array($role, ['company_admin', 'setup_agent', 'company_user'], true)) {
        throw new ApiError('INVALID_ROLE', 'Unbekannte Admin-Rolle');
    }
    if (!$context['is_operator'] && $role !== 'company_user') {
        throw new ApiError('PERMISSION_DENIED', 'Firmen-Admins duerfen nur Benutzer fuer das eigene Panel anlegen');
    }
    if ($manualPassword !== '' && strlen($manualPassword) < 10) {
        throw new ApiError('VALIDATION_ERROR', 'Das Startpasswort muss mindestens 10 Zeichen haben');
    }

    $client = mdAdminClientConnection($auth, $clientId);
    $company = mdAdminCompanyDbForClient($auth, $clientId);
    $preferredLogin = trim($data['login'] ?? '') ?: explode('@', $email)[0];
    $existing = $auth->getOne(
        'SELECT id, login FROM auth."user" WHERE lower(email) = lower(:email) OR login = :login ORDER BY id LIMIT 1',
        [':email' => $email, ':login' => mdAdminSlugLogin($preferredLogin)]
    );
    $existingUserId = $existing ? intval($existing['id']) : null;
    $login = $existing ? $existing['login'] : mdAdminUniqueLogin($auth, $preferredLogin);
    $passwordGenerated = $manualPassword === '';
    $password = $passwordGenerated ? mdAdminGeneratePassword() : $manualPassword;
    $passwordHash = generate_password_hash($login, $password);

    if ($existingUserId) {
        $params = [
            ':id' => $existingUserId,
            ':name' => $name ?: $login,
            ':email' => $email,
        ];
        $passwordSql = '';
        if ($resetPassword) {
            $passwordSql = ', password = :password';
            $params[':password'] = $passwordHash;
        }
        $auth->execute(
            "UPDATE auth.\"user\"
             SET name = :name,
                 email = :email,
                 active = true,
                 mtime = now()
                 $passwordSql
             WHERE id = :id",
            $params
        );
        $userId = $existingUserId;
        if (!$resetPassword) {
            $password = '';
        }
    } else {
        $row = $auth->getOne(
            'INSERT INTO auth."user" (login, password, name, email, active, mtime)
             VALUES (:login, :password, :name, :email, true, now())
             RETURNING id',
            [
                ':login' => $login,
                ':password' => $passwordHash,
                ':name' => $name ?: $login,
                ':email' => $email,
            ]
        );
        $userId = intval($row['id']);
    }

    $auth->execute(
        'INSERT INTO auth.clients_users (client_id, user_id)
         VALUES (:client_id, :user_id)
         ON CONFLICT DO NOTHING',
        [':client_id' => $clientId, ':user_id' => $userId]
    );
    $groupName = mdAdminEnsureGroup($auth, $clientId, $userId, $role);
    mdAdminEnsureEmployee($company, $login, $name ?: $login, $email);

    $token = 'mdinv_' . bin2hex(random_bytes(24));
    $adminUrl = mdAdminPanelUrl();
    $inviteUrl = $adminUrl . '?invite=' . rawurlencode($token);
    $tokenHash = hash('sha256', $token);
    $expiresAt = date('Y-m-d H:i:s', time() + ($expiresDays * 86400));

    $invite = $auth->getOne(
        'INSERT INTO auth.admin_invites (
             client_id, email, login, name, role, status, token_hash, setup_allowed,
             invited_by_user_id, invited_by_login, expires_at, mtime
         )
         VALUES (
             :client_id, :email, :login, :name, :role, :status, :token_hash, :setup_allowed,
             :invited_by_user_id, :invited_by_login, :expires_at, now()
         )
         RETURNING id',
        [
            ':client_id' => $clientId,
            ':email' => $email,
            ':login' => $login,
            ':name' => $name ?: $login,
            ':role' => $role,
            ':status' => 'pending',
            ':token_hash' => $tokenHash,
            ':setup_allowed' => $role === 'setup_agent',
            ':invited_by_user_id' => intval($auth->getUserId()),
            ':invited_by_login' => $auth->getLogin(),
            ':expires_at' => $expiresAt,
        ]
    );

    $credentials = [
        'login' => $login,
        'password' => $password,
        'admin_url' => $adminUrl,
        'invite_url' => $inviteUrl,
        'password_returned_once' => true,
        'password_generated' => $passwordGenerated,
    ];
    $inviteData = [
        'id' => intval($invite['id']),
        'client_name' => $client['name'],
        'email' => $email,
        'name' => $name ?: $login,
        'role' => $role,
        'group' => $groupName,
    ];

    $delivery = ['sent' => false, 'status' => 'NOT_REQUESTED', 'message' => 'E-Mail-Versand wurde nicht angefordert.'];
    if ($sendEmail && $password !== '') {
        $delivery = mdAdminSendInviteMail($company, $inviteData, $credentials);
        $auth->execute(
            'UPDATE auth.admin_invites
             SET email_sent = :sent, email_status = :status, mtime = now()
             WHERE id = :id',
            [
                ':sent' => !empty($delivery['sent']),
                ':status' => $delivery['status'] . ': ' . $delivery['message'],
                ':id' => intval($invite['id']),
            ]
        );
    }

    resultInfo(true, 'INVITE_CREATED', [
        'invite' => $inviteData,
        'credentials' => $credentials,
        'email_delivery' => $delivery,
    ]);
}

function updateCompanyPanelSettings($data) {
    $auth = mdAdminRequireOperator();
    mdAdminEnsureSchema($auth);

    $clientId = intval($data['client_id'] ?? 0);
    if ($clientId <= 0) {
        throw new ApiError('CLIENT_REQUIRED', 'Bitte eine Firma auswaehlen');
    }

    $companyNumber = mdAuthNormalizeCompanyNumber($data['company_number'] ?? '');
    $verificationStatus = trim($data['verification_status'] ?? 'pending');
    $setupStatus = trim($data['setup_status'] ?? 'needs_review');
    $masterDataLocked = mdAdminBool($data['master_data_locked'] ?? true);
    $debugEnabled = mdAdminBool($data['debug_enabled'] ?? false);

    if (!preg_match('/^[0-9]+$/', $companyNumber) || intval($companyNumber) < 2200) {
        throw new ApiError('VALIDATION_ERROR', 'Firmennummer muss eine Zahl ab 2200 sein');
    }
    if (!in_array($verificationStatus, ['pending', 'verified', 'rejected'], true)) {
        throw new ApiError('VALIDATION_ERROR', 'Unbekannter Gewerbepruefstatus');
    }
    if (!in_array($setupStatus, ['needs_review', 'in_setup', 'ready'], true)) {
        throw new ApiError('VALIDATION_ERROR', 'Unbekannter Setupstatus');
    }

    $existingNumber = $auth->getOne(
        'SELECT id FROM auth.clients WHERE company_number = :company_number AND id <> :client_id',
        [':company_number' => $companyNumber, ':client_id' => $clientId]
    );
    if ($existingNumber) {
        throw new ApiError('COMPANY_NUMBER_EXISTS', 'Diese Firmennummer ist bereits vergeben');
    }

    $client = $auth->getOne(
        'UPDATE auth.clients
         SET company_number = :company_number,
             verification_status = :verification_status,
             setup_status = :setup_status,
             master_data_locked = :master_data_locked,
             mtime = now()
         WHERE id = :client_id
           AND COALESCE(is_system, false) = false
         RETURNING id AS code, name, company_number, dbname, is_default,
                   master_data_locked, verification_status, setup_status',
        [
            ':company_number' => $companyNumber,
            ':verification_status' => $verificationStatus,
            ':setup_status' => $setupStatus,
            ':master_data_locked' => $masterDataLocked,
            ':client_id' => $clientId,
        ]
    );
    if (!$client) {
        throw new ApiError('CLIENT_NOT_FOUND', 'Firma wurde nicht gefunden');
    }

    $company = mdAdminCompanyDbForClient($auth, $clientId);
    $company->execute(
        "INSERT INTO defaults_oserp (key, value, mtime)
         VALUES ('debug', :debug_enabled, now())
         ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, mtime = now()",
        [':debug_enabled' => mdAdminBoolValue($debugEnabled)]
    );
    $client = array_merge($client, mdAdminClientDefaults($auth, $clientId));

    resultInfo(true, 'PANEL_SETTINGS_UPDATED', ['client' => $client]);
}

function updateAdminProfile($data) {
    $context = mdAdminRequireHubAccess();
    $auth = $context['auth'];
    $userId = intval($auth->getUserId());
    $name = trim($data['name'] ?? '');
    $email = trim($data['email'] ?? '');
    $themeMode = trim($data['theme_mode'] ?? 'light');
    $adminDebug = mdAdminBool($data['admin_debug'] ?? false);

    if ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL)) {
        throw new ApiError('INVALID_EMAIL', 'Bitte eine gueltige E-Mail-Adresse eintragen');
    }
    if (!in_array($themeMode, ['light', 'dark', 'system'], true)) {
        throw new ApiError('VALIDATION_ERROR', 'Unbekannter Darstellungsmodus');
    }

    $auth->execute(
        'UPDATE auth."user"
         SET name = :name,
             email = :email,
             mtime = now()
         WHERE id = :id',
        [
            ':name' => $name ?: $auth->getLogin(),
            ':email' => $email,
            ':id' => $userId,
        ]
    );
    mdAdminSaveUserConfig($auth, $userId, 'theme_mode', $themeMode);
    mdAdminSaveUserConfig($auth, $userId, 'admin_debug', mdAdminBoolValue($adminDebug));

    resultInfo(true, 'ADMIN_PROFILE_UPDATED', [
        'profile' => mdAdminOperatorProfile($auth),
    ]);
}

function getAdminLogs($data) {
    $context = mdAdminRequireHubAccess();
    $auth = $context['auth'];
    $clientId = intval($data['client_id'] ?? $context['current_client_id']);
    $channel = trim($data['channel'] ?? 'web');

    if ($clientId > 0) {
        mdAdminRequireClientAccess($context, $clientId);
    }
    if (!in_array($channel, ['web', 'database'], true)) {
        throw new ApiError('VALIDATION_ERROR', 'Unbekannter Log-Bereich');
    }

    $client = $clientId > 0 ? mdAdminClientConnection($auth, $clientId) : null;
    if ($channel === 'database') {
        $command = 'docker compose logs --tail=200 db';
        if ($client && !empty($client['dbname'])) {
            $command .= ' # Datenbank: ' . $client['dbname'];
        }
        resultInfo(true, 'DATABASE_LOG_HINT', [
            'channel' => 'database',
            'available' => false,
            'message' => 'PostgreSQL schreibt seine Logs in den Docker-Container. Aus Sicherheitsgruenden liest die Web-App diese Container-Logs noch nicht direkt.',
            'command' => $command,
            'content' => '',
        ]);
        return;
    }

    $logFile = defined('OSERP_DEBUG_LOG_FILE')
        ? OSERP_DEBUG_LOG_FILE
        : __DIR__ . '/../../log/opensource_erp.api.debug.log';
    $log = mdAdminReadTail($logFile);
    resultInfo(true, 'WEB_LOG_LOADED', array_merge($log, [
        'channel' => 'web',
    ]));
}
